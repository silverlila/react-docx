/** pnpm run generate:styles
 *
 *  Writes src/html/docx-default-styles.generated.ts: the styles docx.js writes into every document (its
 *  w:docDefaults and its 13 default styles), as readDocx reads them back from an empty docx.js document.
 *  The HTML preview applies them under the document's own styles (decision 14).
 *  test/html-resolve.test.ts repeats these steps and fails when the committed file drifts, e.g. after a
 *  docx.js upgrade. */

import { readFileSync, writeFileSync } from "node:fs";
import { renderToBuffer } from "../src/index";
import { readDocx } from "../src/read/index";
import type { DocumentNode } from "../src/schema/elements";

const OUT = "src/html/docx-default-styles.generated.ts";

const EMPTY: DocumentNode = {
  type: "Document",
  props: {},
  children: [{ type: "Section", props: {}, children: [{ type: "Paragraph", props: {}, children: [] }] }],
};

function docxVersion(): string {
  const manifest: unknown = JSON.parse(readFileSync("node_modules/docx/package.json", "utf8"));
  if (typeof manifest !== "object" || manifest === null || !("version" in manifest)) {
    throw new Error("node_modules/docx/package.json has no version");
  }
  return String(manifest.version);
}

async function main(): Promise<void> {
  const { document } = readDocx(new Uint8Array(await renderToBuffer(EMPTY)));
  const styles = document.props.styles ?? {};
  const source =
    `/** Generated by scripts/generate-default-styles.ts from docx ${docxVersion()}. Do not edit:\n` +
    " *  run `pnpm run generate:styles`. */\n\n" +
    'import type { StylesProps } from "../schema/elements";\n\n' +
    `export const DOCX_DEFAULT_STYLES: StylesProps = ${JSON.stringify(styles, null, 2)};\n`;
  writeFileSync(OUT, source);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
